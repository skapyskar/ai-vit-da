import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";

const scenes = [
  {
    text: "8-Puzzle Solver — Aayush Dwivedi, 24BCT0058. Algorithm 3: Depth Limited Search. The task is to move the blank until the board matches the goal.",
    seconds: 24,
    action: async (page) => page.goto("http://127.0.0.1:8080/"),
  },
  {
    text: "Enter the initial and goal states using 0–8 once each. 0 is the blank. The depth limit bounds each branch. A random puzzle is generated by legal moves from the goal.",
    seconds: 26,
    action: async (page) => page.locator("#depth-limit").fill("2"),
  },
  {
    text: "Next expands the root. DLS tries Up, Right, Down, Left. The frontier is a stack. Only states on the active path are skipped; the closed list shows expanded visits.",
    seconds: 32,
    action: async (page) => {
      await page.locator("#next").click();
      await page.locator(".trace-section").scrollIntoViewIfNeeded();
    },
  },
  {
    text: "At limit 2 the solution is Down, then Right. Cost = 2. Generated: 11; expanded: 4. Time excludes playback, and memory is estimated. Play solution shows the legal moves.",
    seconds: 30,
    action: async (page) => {
      await page.locator("#speed").selectOption("0");
      await page.locator("#pause").click();
      await page.locator("#result").waitFor({ state: "visible" });
      await page.locator("#result").scrollIntoViewIfNeeded();
      await page.locator("#play-solution").click();
    },
  },
  {
    text: "At limit 1, the search returns a cutoff. The bound stopped further exploration; it does not prove the puzzle is unsolvable. A parity mismatch is rejected before searching.",
    seconds: 25,
    action: async (page) => {
      await page.locator("#reset").click();
      await page.locator("#depth-limit").fill("1");
      await page.locator("#run").click();
      await page.locator("#result").waitFor({ state: "visible" });
      await page.locator("#result").scrollIntoViewIfNeeded();
    },
  },
  {
    text: "These are separate DLS runs on the same puzzle at limits 0, 2, 4 and 8. Larger limits can expand more nodes before finding the same solution. Other algorithms are not assigned.",
    seconds: 30,
    action: async (page) => {
      await page.goto("http://127.0.0.1:8080/#compare");
      await page.locator("#compare-run").click();
      await page.waitForFunction(
        () =>
          document.querySelector("#comparison-status").textContent ===
          "Comparison complete.",
      );
    },
  },
  {
    text: "DLS is uninformed and uses no heuristic. Time: O(b^ℓ). Search space: O(bℓ). It finds goals within the limit if allowed to finish, but does not guarantee a shortest path.",
    seconds: 30,
    action: async (page) => page.goto("http://127.0.0.1:8080/#algorithm"),
  },
];
await mkdir("tmp/demo", { recursive: true });
const browser = await chromium.launch({
  channel: "chromium",
  executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH,
});
const context = await browser.newContext({
  viewport: { width: 1440, height: 1000 },
  recordVideo: { dir: "tmp/demo", size: { width: 1440, height: 1000 } },
});
const page = await context.newPage();
const video = page.video();
for (let i = 0; i < scenes.length; i++) {
  await scenes[i].action(page);
  await page.evaluate((text) => {
    document.querySelector("#demo-caption")?.remove();
    const caption = document.createElement("div");
    caption.id = "demo-caption";
    caption.textContent = text;
    caption.style.cssText =
      "position:fixed;bottom:0;left:0;right:0;background:#111;color:#eee;border-top:2px solid #bc2929;padding:12px 28px;font:16px/1.5 Arial,sans-serif;z-index:2";
    document.body.append(caption);
  }, scenes[i].text);
  console.log("Scene " + (i + 1) + "/" + scenes.length);
  await page.waitForTimeout(scenes[i].seconds * 1000);
}
await context.close();
await video.saveAs("tmp/demo/walkthrough.webm");
await browser.close();
execFileSync("ffmpeg", [
  "-y",
  "-loglevel",
  "error",
  "-i",
  "tmp/demo/walkthrough.webm",
  "-c:v",
  "libx264",
  "-preset",
  "fast",
  "-crf",
  "26",
  "-pix_fmt",
  "yuv420p",
  "-an",
  "-movflags",
  "+faststart",
  "docs/24BCT0058-dls-demo.mp4",
]);
console.log("Saved demonstration video.");
